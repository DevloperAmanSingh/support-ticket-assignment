-- Section 1 of the design: six tables, CHECK constraints, the composite FK, and two indexes.

CREATE TYPE enum_tickets_status AS ENUM ('open', 'closed', 'unassigned');
CREATE TYPE enum_decisions_outcome AS ENUM ('assigned', 'unassigned');

CREATE TABLE companies (
  id       text PRIMARY KEY,
  name     text NOT NULL,
  timezone text NOT NULL
);

CREATE TABLE agents (
  id           text PRIMARY KEY,
  company_id   text NOT NULL REFERENCES companies (id),
  name         text NOT NULL,
  timezone     text NOT NULL,
  ticket_limit integer NOT NULL DEFAULT 5,
  CONSTRAINT agents_company_id_id_key UNIQUE (company_id, id),
  CONSTRAINT agents_ticket_limit_check CHECK (ticket_limit >= 1)
);

CREATE TABLE shifts (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agent_id     text NOT NULL REFERENCES agents (id) ON DELETE CASCADE,
  weekday      smallint NOT NULL,
  start_minute smallint NOT NULL,
  end_minute   smallint NOT NULL,
  CONSTRAINT shifts_weekday_check CHECK (weekday BETWEEN 0 AND 6),
  CONSTRAINT shifts_start_minute_check CHECK (start_minute BETWEEN 0 AND 1439),
  CONSTRAINT shifts_end_minute_check CHECK (end_minute BETWEEN 0 AND 1439),
  CONSTRAINT shifts_start_end_check CHECK (start_minute <> end_minute)
);
CREATE INDEX shifts_agent_id_idx ON shifts (agent_id);

CREATE TABLE coverage_hours (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id   text NOT NULL REFERENCES companies (id),
  weekday      smallint NOT NULL,
  start_minute smallint NOT NULL,
  end_minute   smallint NOT NULL,
  CONSTRAINT coverage_hours_weekday_check CHECK (weekday BETWEEN 0 AND 6),
  CONSTRAINT coverage_hours_start_minute_check CHECK (start_minute BETWEEN 0 AND 1439),
  CONSTRAINT coverage_hours_end_minute_check CHECK (end_minute BETWEEN 1 AND 1440),
  CONSTRAINT coverage_hours_start_end_check CHECK (start_minute < end_minute)
);
CREATE INDEX coverage_hours_company_id_idx ON coverage_hours (company_id);

CREATE TABLE decisions (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id text NOT NULL REFERENCES companies (id),
  ticket_id  text NOT NULL,
  decided_at timestamptz NOT NULL,
  outcome    enum_decisions_outcome NOT NULL,
  reason     jsonb NOT NULL
);

CREATE TABLE tickets (
  company_id  text NOT NULL REFERENCES companies (id),
  ticket_id   text NOT NULL,
  status      enum_tickets_status NOT NULL,
  agent_id    text,
  created_at  timestamptz NOT NULL,
  assigned_at timestamptz,
  closed_at   timestamptz,
  decision_id integer NOT NULL REFERENCES decisions (id),
  PRIMARY KEY (company_id, ticket_id),
  CONSTRAINT tickets_company_agent_fkey
    FOREIGN KEY (company_id, agent_id) REFERENCES agents (company_id, id),
  CONSTRAINT tickets_open_check
    CHECK (status <> 'open' OR (agent_id IS NOT NULL AND assigned_at IS NOT NULL)),
  CONSTRAINT tickets_unassigned_check
    CHECK (status <> 'unassigned' OR (agent_id IS NULL AND assigned_at IS NULL)),
  CONSTRAINT tickets_closed_check
    CHECK (status <> 'closed' OR closed_at IS NOT NULL),
  CONSTRAINT tickets_agent_assigned_check
    CHECK ((agent_id IS NULL) = (assigned_at IS NULL))
);

CREATE INDEX tickets_agent_status_idx ON tickets (agent_id, status);
CREATE INDEX tickets_company_status_created_idx
  ON tickets (company_id, status, created_at, ticket_id);
